    func testSameConnectionTransactionSupportsRegistryAndFutureMarkerAtomically() async throws {
        let store = try store(), value = try record()
        let connection = try SQLiteConnection(url: fixtureURL(for: store))
        defer { connection.close() }
        enum FixtureFailure: Error { case abort }
        XCTAssertThrowsError(try connection.transaction {
            try ImportedIdentityRegistrySQL.apply(.upsert(value), connection: connection)
            try connection.execute("INSERT INTO settings (key, value) VALUES (?, ?)",
                bindings: [.text("fixture.future-migration-marker"), .blob(Data("true".utf8))])
            throw FixtureFailure.abort
        })
        try await expectRows(store, [])
        let marker = try await store.setting(forKey: "fixture.future-migration-marker")
        XCTAssertNil(marker)
        try connection.transaction {
            try ImportedIdentityRegistrySQL.apply(.upsert(value), connection: connection)
            try connection.execute("INSERT INTO settings (key, value) VALUES (?, ?)",
                bindings: [.text("fixture.future-migration-marker"), .blob(Data("true".utf8))])
        }
        try await expectRows(store, [value])
        let committed = try await store.setting(forKey: "fixture.future-migration-marker")
        XCTAssertEqual(committed, .bool(true))
    }
