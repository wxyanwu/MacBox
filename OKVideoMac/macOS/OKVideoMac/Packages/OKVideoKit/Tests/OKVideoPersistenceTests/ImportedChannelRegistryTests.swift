                        upstream: String? = nil, lifecycle: ImportedChannelRegistryLifecycle = .active,
                        provenance: ImportedSourceProvenance = .verified,
                        updated: Date? = nil, created: Date? = nil, version: Int = 1, evidenceVersion: Int = 1) throws -> ImportedChannelRegistryRecord {
        ImportedChannelRegistryRecord(identity: try ImportedLiveChannelIdentity(source: source ?? self.source, localID: token(n)),
