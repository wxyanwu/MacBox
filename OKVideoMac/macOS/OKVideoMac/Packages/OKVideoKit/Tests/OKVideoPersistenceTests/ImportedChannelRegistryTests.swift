    private func url() throws -> URL {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("OKVideoRegistryTests-\(UUID())")
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        addTeardownBlock { try? FileManager.default.removeItem(at: directory) }
        return directory.appendingPathComponent("fixture.sqlite3")
    }
    private var fixtureURLs: [ObjectIdentifier: URL] = [:]
    private func store() throws -> SQLiteStore {
        let path = try url()
        let store = try SQLiteStore(databaseURL: path)
        fixtureURLs[ObjectIdentifier(store)] = path
        return store
    }
    private func fixtureURL(for store: SQLiteStore) -> URL { fixtureURLs[ObjectIdentifier(store)]! }
    private func expectRows(_ store: SQLiteStore, _ expected: [ImportedChannelRegistryRecord], source: LiveSourceID? = nil,
                            file: StaticString = #filePath, line: UInt = #line) async throws {
        let rows = try await store.importedChannelIdentities(for: source ?? self.source)
        XCTAssertEqual(rows, expected, file: file, line: line)
    }
    private func fails(_ expected: ImportedChannelRegistryError? = nil, file: StaticString = #filePath, line: UInt = #line,
                       _ operation: () async throws -> Void) async {
        do { try await operation(); XCTFail("Expected failure", file: file, line: line) }
        catch { if let expected { XCTAssertEqual(error as? ImportedChannelRegistryError, expected, file: file, line: line) } }
    }
    private func scalar(_ url: URL, _ sql: String) throws -> Int {
        let connection = try SQLiteConnection(url: url)
        defer { connection.close() }
        return try connection.scalarInt(sql)
    }
    private func execute(_ url: URL, _ sql: String, _ bindings: [SQLiteBinding] = []) throws {
        let connection = try SQLiteConnection(url: url)
        defer { connection.close() }
        try connection.execute(sql, bindings: bindings)
    }
    private func evidenceData(_ url: URL) throws -> Data {
        let connection = try SQLiteConnection(url: url)
        defer { connection.close() }
        var result: Data?
        try connection.query("SELECT evidence FROM \(table) ORDER BY local_id LIMIT 1") { result = connection.data($0, 0) }
        return try XCTUnwrap(result)
    }
    private func replaceEvidence(_ url: URL, _ data: Data) throws {
        try execute(url, "UPDATE \(table) SET evidence = ?", [.blob(data)])
    }
    /// Strip only the new schema in a temporary fixture. All older tables retain
